# memory-kit :: start.ps1  (ASCII only, PowerShell 5.1)
# One-shot entry: ensure an embedding endpoint -> ensure venv -> serve HTTP on kit.json port.
# Embedding chain (first healthy wins):
#   1. on-stick local-ai engine (..\local-ai\start-local-ai.ps1 -NoChat)  <- works offline
#   2. SSH tunnel to the LAN server (config\secret.ps1)
#   3. none -> search degrades to keyword-only (sparse)
# Pipeline (run manually when logs change):
#   collect.ps1 -> chunk.py -> embed.py -> organize.py   then start.ps1
$ErrorActionPreference = 'Stop'
$kit = Split-Path -Parent $MyInvocation.MyCommand.Path
$cfg = Get-Content (Join-Path $kit 'config\kit.json') -Raw | ConvertFrom-Json

function Test-Endpoint([string]$healthUrl) {
  try {
    $r = Invoke-WebRequest -Uri $healthUrl -UseBasicParsing -TimeoutSec 3
    return ($r.StatusCode -eq 200)
  } catch { return $false }
}

function Find-Endpoint {
  foreach ($ep in $cfg.embed.endpoints) {
    if (Test-Endpoint $ep.health) { return $ep }
  }
  return $null
}

# ---------- 1. embedding endpoint ----------
$live = Find-Endpoint

if (-not $live) {
  # 1a. on-stick engine
  $localStart = Join-Path (Split-Path -Parent $kit) 'local-ai\start-local-ai.ps1'
  if (Test-Path $localStart) {
    Write-Output 'no endpoint up -> starting on-stick local-ai embedding engine (offline capable)'
    # Launch it as its OWN process and poll health. Never pipe this child, and never use
    # Start-Process -Wait: in PowerShell 5.1 -Wait follows the process tree, so the
    # llama-server grandchild (a daemon) would keep this script blocked forever.
    try {
      Start-Process -FilePath 'powershell' -WindowStyle Hidden -ArgumentList @(
        '-NoProfile','-ExecutionPolicy','Bypass','-File',$localStart,'-NoChat','-NoBrowser') | Out-Null
    } catch { Write-Output ('local-ai launch failed: ' + $_.Exception.Message) }
    $deadline = (Get-Date).AddSeconds(240)
    while ((Get-Date) -lt $deadline) {
      $live = Find-Endpoint
      if ($live) { break }
      Start-Sleep -Seconds 1
    }
    if ($live) { Write-Output ('on-stick engine healthy: ' + $live.url) }
    else { Write-Output 'WARN on-stick engine did not come up within 240s' }
  } else {
    Write-Output ('no local-ai engine at ' + $localStart)
  }
} else { Write-Output ('embedding endpoint already healthy: ' + $live.url) }

if (-not $live) {
  # 1b. SSH tunnel to the LAN server
  $secret = Join-Path $kit 'config\secret.ps1'
  if (-not (Test-Path $secret)) {
    Write-Output 'WARN no config\secret.ps1 and no local engine -> search degrades to sparse (keyword only).'
  } else {
    . $secret   # defines $KitTunnelPw
    $t = $cfg.tunnel
    Write-Output ('opening SSH tunnel {0} -> {1}:{2} ...' -f $t.local_port, $t.remote_host, $t.remote_port)
    Start-Process -WindowStyle Hidden -FilePath $t.plink -ArgumentList @(
      '-batch','-ssh','-hostkey', $t.hostkey, '-pw', $KitTunnelPw,
      '-L', ('{0}:{1}:{2}' -f $t.local_port, $t.remote_host, $t.remote_port),
      '-N', $t.user )
    $ok = $false
    foreach ($i in 1..12) {
      Start-Sleep 2
      if (Find-Endpoint) { $ok = $true; break }
      # remote llama-server may still be loading the model (503)
    }
    if ($ok) { Write-Output 'tunnel up, embedding endpoint healthy' }
    else { Write-Output 'WARN tunnel open but endpoint not healthy yet (model may be loading). Search may degrade to sparse.' }
  }
}

# ---------- 2. venv ----------
$py = Join-Path $kit 'runtime\venv\Scripts\python.exe'
if (-not (Test-Path $py)) {
  Write-Output 'venv missing -> creating via uv (first use on this machine, few minutes)'
  $uv = Join-Path $kit 'runtime\uv.exe'
  if (-not (Test-Path $uv)) { $uv = 'uv' }
  $runtime = Join-Path $kit 'runtime'
  New-Item -ItemType Directory -Force -Path $runtime | Out-Null
  & $uv venv (Join-Path $runtime 'venv') --python 3.11
  if ($LASTEXITCODE -ne 0) { throw 'uv venv failed - install uv or put runtime\uv.exe on the stick' }
  # pypi.org unreachable from CN network - use Tsinghua mirror (verified 2026-10-24)
  & $uv pip install --python $py --index-url https://pypi.tuna.tsinghua.edu.cn/simple -r (Join-Path $kit 'requirements.txt')
  if ($LASTEXITCODE -ne 0) { throw 'pip install failed' }
}

# jieba cache stays on the stick (not the host temp dir)
$env:JIEBA_CACHE_DIR = Join-Path $kit 'runtime\jieba-cache'
$tmpDir = Join-Path $kit 'runtime\tmp'
New-Item -ItemType Directory -Force -Path $tmpDir | Out-Null
$env:TMP = $tmpDir
$env:TEMP = $tmpDir

# resolved MCP config for THIS machine (drive letters may differ per machine)
$mcpDir = Join-Path $kit 'mcp'
New-Item -ItemType Directory -Force -Path $mcpDir | Out-Null
$resolved = @{
  mcpServers = @{
    'memory-kit' = @{
      command = $py
      args = @((Join-Path $kit 'bin\mcp_server.py'))
      note = 'regenerated by start.ps1 on each launch; paste into ZCode/codex MCP config'
    }
  }
}
[IO.File]::WriteAllText((Join-Path $mcpDir 'memory-kit.resolved.json'),
  ($resolved | ConvertTo-Json -Depth 5), (New-Object System.Text.UTF8Encoding($false)))

# ---------- 3. serve ----------
$port = $cfg.search.port
Write-Output ("memory-kit -> http://127.0.0.1:{0}   (close this window to stop)" -f $port)
& $py (Join-Path $kit 'bin\serve.py')
